    private void tampilData(String where) {
         try {
            stat = con.createStatement();
            tabModel.getDataVector().removeAllElements();
            tabModel.fireTableDataChanged();
            rs = stat.executeQuery("SELECT * FROM tblservices" + where);
            
            while (rs.next()) {
                Object[] data = {
                    rs.getString("idServ"),
                    rs.getString("nama"),
                    rs.getString("alamat"),
                    rs.getString("no_tlp"),
                    rs.getString("jenPelayanan"),
                    rs.getString("beratBaju"),
                    rs.getString("totalHarga"),
                };
                
                tabModel.addRow(data);
            }
        } catch (SQLException e) {
            e.printStackTrace();
        }
    }
