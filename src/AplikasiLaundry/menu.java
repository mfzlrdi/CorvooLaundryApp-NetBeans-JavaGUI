    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        if (inpNama.getText().equals("") || inpAlamat.getText().equals("") || inpTelp.getText().equals("") || comboLayanan.getSelectedItem().equals("") || inpBerat.getText().equals("") || totalH.getText().equals(""))  {
            JOptionPane.showMessageDialog(null, "LENGKAPI DATA !!", "Laundry Corvoo", JOptionPane.INFORMATION_MESSAGE);
        } else {
            try {
                stat = con.createStatement();
                stat.executeUpdate("UPDATE tblservices SET " 
                        + "nama = '" + inpNama.getText() + "', "
                        + "alamat = '" + inpAlamat.getText() + "', "
                        + "no_tlp = '" + inpTelp.getText() + "', "
                        + "jenPelayanan = '" + comboLayanan.getSelectedItem() + "', "
                        + "hargaBarang = '" + inpHarga.getText() + "', "
                        + "beratBaju = '" + inpBerat.getText() + "', "
                        + "totalHarga = '" + totalH.getText() + "' "
                        + "WHERE idServ = '" + idLayan.getText() + "'");
                idServeIncrement();
                tampilData("");
                JOptionPane.showMessageDialog(null, "Data Barang Berhasil di Edit");
                batal();
                btnSimpan.setEnabled(true);
                btnEdit.setEnabled(true);
                btnHapus.setEnabled(true);
                btnBatal.setEnabled(true);
            } catch (Exception e) {
                e.printStackTrace();
            } finally {
                inpNama.setText("");
                inpAlamat.setText("");
                inpTelp.setText("");
                comboLayanan.setSelectedItem("");
                inpHarga.setText("");
                inpBerat.setText("");
                totalH.setText("");
                JOptionPane.showMessageDialog(null, "Data Berhasil Di Edit ", "Laundry Corvoo", JOptionPane.INFORMATION_MESSAGE);
                tampilData("");
            }
        }
    }//GEN-LAST:event_btnEditActionPerformed

