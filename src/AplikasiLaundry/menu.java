    private void btnHitungActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHitungActionPerformed

        try {
            if (inpNama.getText().equals("") || inpAlamat.getText().equals("") || inpTelp.getText().equals("") || comboLayanan.getSelectedItem().equals("") || inpBerat.getText().equals(""))  {
                JOptionPane.showMessageDialog(null, "LENGKAPI DATA !!", "Laundry Corvoo", JOptionPane.INFORMATION_MESSAGE);
            } else {
                int berat = Integer.parseInt(inpBerat.getText().toString());
                int hargaCuci = (int) Double.parseDouble(inpHarga.getText().toString());
                int jumlah = berat * hargaCuci;

                // Membuat cek jika hari ini jumat
                Calendar kalen = Calendar.getInstance();
                int perminggu = kalen.get(Calendar.DAY_OF_WEEK);

                // Definisikan diskon
                double disk = 0.0;
                String pemilihanDisk = comboLayanan.getSelectedItem().toString();
                if (perminggu == Calendar.FRIDAY) {
                    switch (pemilihanDisk) {
                        case "Cuci-Setrika":
                            disk = 0.08;
                            break;
                        case "Cuci":
                            disk = 0.05;
                            break;
                        case "Strika":
                            disk = 0.05;
                            break;
                    }
                }

                // mendapatkan diskon jika di hari jumat
                if (disk > 0.0) {
                    jumlah = jumlah - (int) (jumlah * disk);
                }

                totalH.setText(Integer.toString(jumlah));
            }
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(null, ex);
        }
    }//GEN-LAST:event_btnHitungActionPerformed

